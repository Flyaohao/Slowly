def seed_knowledge():
    db = SessionLocal()
    try:
        count = 0
        for doc_data in KNOWLEDGE_DOCS:
            doc_id = seed_document(
                db,
                title=doc_data["title"],
                source=doc_data["source"],
                content=doc_data["content"],
            )
            count += 1
            print(f"创建知识文档: {doc_data['title']} (id={doc_id})")
        db.commit()
        print(f"已创建 {count} 个知识文档")
    except Exception as e:
        db.rollback()
        print(f"错误: {e}")
        raise
    finally:
        db.close()


if __name__ == "__main__":
    seed_knowledge()
